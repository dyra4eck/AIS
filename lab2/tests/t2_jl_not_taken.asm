; Тест 2. Условный переход JL, условие ложно (переход не выполняется).
; JL стоит в конвейерах 0, 1 и 2. Проверяется, что:
;  - переход не выполняется при a = b, a > b и при a > b с переполнением
;    (30000 - (-30000): N=1, V=1, N xor V = 0);
;  - команды, следующие за JL в той же группе и в следующих группах, выполняются;
;  - JL использует флаги более ранней команды своей группы (слоты 0 -> 1 -> 2)
;    и не использует флаги более поздней команды своей группы.
; При ошибке управление попадает на метку fail, которая портит DM[8].

.data
.org 0
        .word 1          ; 0: константа 1
        .word 30000      ; 1
        .word -30000     ; 2
.org 8
        .fill 4, 0       ; 8..11: маркеры, должны стать равны 1

.text
; G0
        LOAD  R1, (R0)   ; R1 = 1
        NOP 2
; G1
        NOP 3
; G2
        LOAD  R2, (R1)   ; R2 = 30000
        ADD   R3, R1     ; R3 = 1
        ADD   R8, R1     ; R8 = 1
; G3
        NOP 3
; G4
        ADD   R3, R1     ; R3 = 2
        ADD   R8, R8     ; R8 = 2
        NOP
; G5
        NOP 3
; G6
        LOAD  R4, (R3)   ; R4 = -30000
        ADD   R8, R8     ; R8 = 4
        NOP
; G7
        NOP 3
; G8
        ADD   R8, R8     ; R8 = 8
        ADD   R5, R2     ; R5 = 30000
        ADD   R6, R2     ; R6 = 30000
; G9
        ADD   R7, R4     ; R7 = -30000
        NOP 2
; G10
        ADD   R9, R8     ; R9  = 8
        ADD   R10, R8    ; R10 = 8
        ADD   R11, R8    ; R11 = 8
; G11
        NOP 3
; G12
        ADD   R9, R1     ; R9  = 9
        ADD   R10, R3    ; R10 = 10
        ADD   R11, R3    ; R11 = 10
; G13
        NOP 3
; G14: JL в конвейере 1, флаги от SUB в конвейере 0 той же группы
        SUB   R5, R6     ; 30000 - 30000 = 0: Z=1, N=0, V=0 -> не "<"
        JL    fail       ; не выполняется
        STORE R1, (R8)   ; DM[8] = 1 - выполняется
; G15: JL в конвейере 0, флаги из регистра флагов (от G14);
;      более поздний SUB той же группы даёт "<", но не должен влиять на JL
        JL    fail       ; не выполняется
        SUB   R4, R2     ; -30000 - 30000 = 5536 (V=1, N=0 -> "<")
        STORE R1, (R9)   ; DM[9] = 1
; G16: JL в конвейере 2, флаги от SUB в конвейере 0 той же группы
        SUB   R2, R7     ; 30000 - (-30000) = -5536 (V=1, N=1 -> не "<")
        ADD   R11, R1    ; R11 = 11
        JL    fail       ; не выполняется
; G17
        STORE R1, (R10)  ; DM[10] = 1
        SUB   R3, R1     ; 2 - 1 = 1 -> не "<"
        JL    fail       ; не выполняется
; G18
        STORE R1, (R11)  ; DM[11] = 1
        NOP
        HALT

fail:
        STORE R7, (R8)   ; DM[8] = -30000 - признак ошибки
        HALT
