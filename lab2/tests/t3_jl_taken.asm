; Тест 3. Условный переход JL, условие истинно (переход выполняется).
; JL стоит в конвейерах 0, 1 и 2. Проверяется, что:
;  - управление передаётся по адресу перехода (вперёд);
;  - команды неверного пути - более поздние команды той же группы и две
;    следующие группы (в режиме predict они уже выбраны и находятся на
;    ступенях OF и IF) - аннулируются и не меняют память, регистры и флаги;
;  - переход выполняется и при переполнении (-30000 - 30000: V=1, N=0).
; Команды неверного пути записывают в память "мусор" (BAD = 0BADh).

.data
.org 0
        .word 1          ; 0: константа 1
        .word 5          ; 1
        .word 7          ; 2
        .word 0x0BAD     ; 3: BAD
        .word 30000      ; 4
        .word -30000     ; 5
.org 8
        .fill 8, 0       ; 8..15: маркеры

.text
; G0
        LOAD  R1, (R0)   ; R1 = 1
        NOP 2
; G1
        NOP 3
; G2
        LOAD  R2, (R1)   ; R2 = 5
        ADD   R3, R1     ; R3 = 1
        ADD   R8, R1     ; R8 = 1
; G3
        NOP 3
; G4
        ADD   R3, R1     ; R3 = 2
        ADD   R8, R8     ; R8 = 2
        ADD   R4, R2     ; R4 = 5 (адрес)
; G5
        NOP 3
; G6
        LOAD  R5, (R3)   ; R5 = 7
        ADD   R8, R8     ; R8 = 4
        ADD   R3, R1     ; R3 = 3
; G7
        NOP 3
; G8
        ADD   R8, R8     ; R8 = 8
        LOAD  R6, (R3)   ; R6 = BAD
        LOAD  R7, (R4)   ; R7 = -30000
; G9
        SUB   R4, R1     ; R4 = 4
        NOP 2
; G10
        ADD   R9, R8     ; R9  = 8
        ADD   R10, R8    ; R10 = 8
        ADD   R11, R8    ; R11 = 8
; G11
        LOAD  R12, (R4)  ; R12 = 30000
        NOP 2
; G12
        ADD   R9, R1     ; R9  = 9
        ADD   R10, R3    ; R10 = 11
        ADD   R11, R2    ; R11 = 13
; G13
        NOP 3
; ---- случай 1: JL в конвейере 2, флаги от SUB в конвейере 0 той же группы
; G14
        SUB   R2, R5     ; 5 - 7 = -2 -> "<"
        STORE R1, (R8)   ; DM[8] = 1 (до перехода - выполняется)
        JL    t1
; G15 (неверный путь, ступень OF в момент перехода)
        STORE R6, (R9)   ; не должна выполниться
        STORE R6, (R10)  ; не должна выполниться
        ADD   R1, R6     ; не должна выполниться (иначе R1 испорчен)
; G16 (неверный путь, ступень IF в момент перехода)
        STORE R6, (R11)  ; не должна выполниться
        SUB   R12, R7    ; не должна выполниться (изменила бы флаги)
        STORE R6, (R8)
t1:                     ; G17
        STORE R1, (R9)   ; DM[9] = 1
        NOP 2
; G18
        NOP 3
; ---- случай 2: JL в конвейере 0, флаги из регистра флагов (от G14)
; G19
        JL    t2
        STORE R6, (R10)  ; неверный путь в той же группе
        STORE R6, (R11)  ; неверный путь в той же группе
; G20
        STORE R6, (R8)   ; неверный путь
        NOP 2
t2:                     ; G21
        STORE R1, (R10)  ; DM[11] = 1
        ADD   R10, R1    ; R10 = 12
        NOP
; G22
        NOP 3
; ---- случай 3: JL в конвейере 1, переполнение: -30000 - 30000 = 5536, V=1, N=0 -> "<"
; G23
        SUB   R7, R12    ; флаги: "<"
        JL    t3
        STORE R6, (R11)  ; неверный путь в той же группе
; G24
        STORE R6, (R8)   ; неверный путь
        NOP 2
; G25
        STORE R6, (R9)   ; неверный путь
        NOP 2
t3:                     ; G26
        STORE R1, (R10)  ; DM[12] = 1
        STORE R7, (R11)  ; DM[13] = 5536 (результат SUB в группе с переходом записан)
        HALT
