; Тест 4. Флаги и несколько переходов в одной группе.
; Проверяется, что:
;  - SUB в более позднем (аннулированном) слоте группы с выполненным переходом
;    не меняет ни регистр, ни флаги;
;  - JL в конвейере 0 следующей группы видит флаги предыдущей группы;
;  - в группе "JL (не выполняется), SUB, JL" второй JL видит флаги этого SUB;
;  - в группе с двумя выполняемыми переходами выполняется только первый.

.data
.org 0
        .word 1          ; 0: константа 1
        .word 5          ; 1
        .word 7          ; 2
        .word 0x0BAD     ; 3: BAD
.org 8
        .fill 4, 0       ; 8..11: результаты

.text
; G0
        LOAD  R1, (R0)   ; R1 = 1
        NOP 2
; G1
        NOP 3
; G2
        LOAD  R2, (R1)   ; R2 = 5
        ADD   R3, R1     ; R3 = 1
        ADD   R8, R1     ; R8 = 1
; G3
        NOP 3
; G4
        ADD   R3, R1     ; R3 = 2
        ADD   R8, R8     ; R8 = 2
        NOP
; G5
        NOP 3
; G6
        LOAD  R4, (R3)   ; R4 = 7
        ADD   R8, R8     ; R8 = 4
        ADD   R3, R1     ; R3 = 3
; G7
        NOP 3
; G8
        ADD   R8, R8     ; R8 = 8
        LOAD  R6, (R3)   ; R6 = BAD
        NOP
; G9
        NOP 3
; G10
        ADD   R9, R8     ; R9  = 8
        ADD   R10, R8    ; R10 = 8
        ADD   R11, R8    ; R11 = 8
; G11
        NOP 3
; G12
        ADD   R9, R1     ; R9  = 9
        ADD   R10, R3    ; R10 = 11
        ADD   R11, R3    ; R11 = 11
; G13
        NOP 3
; G14: SUB (<), JL (выполняется), SUB в аннулируемом слоте (дал бы "не <")
        SUB   R2, R4     ; 5 - 7 = -2 -> "<"
        JL    l1
        SUB   R4, R1     ; аннулируется: R4 должен остаться 7, флаги - "<"
; G15 (неверный путь)
        STORE R6, (R8)
        NOP 2
; G16 (неверный путь)
        STORE R6, (R9)
        NOP 2
l1:                     ; G17: JL в конвейере 0 - флаги из регистра флагов ("<")
        JL    l2         ; должен выполниться
        STORE R6, (R8)   ; неверный путь
        NOP
; G18
        NOP 3
; G19
        STORE R6, (R9)   ; неверный путь
        NOP 2
l2:                     ; G20
        STORE R1, (R8)   ; DM[8] = 1
        STORE R4, (R9)   ; DM[9] = 7 (аннулированный SUB не изменил R4)
        SUB   R1, R2     ; 1 - (-2) = 3 -> не "<"
; G21: JL в конвейере 0 - флаги соседней группы (G20: не "<")
        JL    fail       ; не выполняется
        NOP 2
; G22: JL (не выполняется), SUB (<), JL (выполняется)
        JL    fail       ; флаги от G20: не "<"
        SUB   R2, R4     ; -2 - 7 = -9 -> "<"
        JL    l3         ; видит флаги SUB из слота 1 -> выполняется
; G23, G24 (неверный путь)
        STORE R6, (R10)
        NOP 2
        STORE R6, (R11)
        NOP 2
l3:                     ; G25: два выполняемых перехода в одной группе
        JL    l4         ; выполняется первый
        JL    fail       ; аннулируется
        STORE R6, (R10)  ; аннулируется
; G26, G27 (неверный путь)
        STORE R6, (R11)
        NOP 2
        STORE R6, (R10)
        NOP 2
l4:                     ; G28
        STORE R1, (R10)  ; DM[11] = 3
        NOP
        HALT

fail:
        STORE R6, (R8)   ; признак ошибки
        HALT
