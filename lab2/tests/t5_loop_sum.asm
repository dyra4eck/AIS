; Тест 5. Цикл: сумма элементов массива из 8 чисел.
; Переход назад выполняется 7 раз, на последней итерации - не выполняется.
; Счётчик итераций R7 идёт от -8 до 0: флаги ADD R7,R1 дают "<", пока R7 < 0.

.data
.org 0
        .word 1          ; 0: константа 1
        .word array      ; 1: адрес массива
        .word -8         ; 2: -N
        .word result     ; 3: адрес результата
.org 16
array:  .word 3, -1, 10, 250, -7, 1000, 42, 0x100
result: .word 0, 0       ; сумма, число итераций

.text
; G0
        LOAD  R1, (R0)   ; R1 = 1
        NOP 2
; G1
        NOP 3
; G2
        LOAD  R2, (R1)   ; R2 = адрес массива
        ADD   R10, R1    ; R10 = 1
        NOP
; G3
        NOP 3
; G4
        ADD   R10, R1    ; R10 = 2
        NOP 2
; G5
        NOP 3
; G6
        LOAD  R7, (R10)  ; R7 = -8
        ADD   R10, R1    ; R10 = 3
        NOP
; G7
        NOP 3
; G8
        LOAD  R3, (R10)  ; R3 = адрес результата
        NOP 2
; G9
        NOP 3
loop:                   ; G10
        LOAD  R5, (R2)   ; R5 = очередной элемент
        ADD   R2, R1     ; указатель++
        ADD   R8, R1     ; число итераций++
; G11
        NOP 3
; G12
        ADD   R4, R5     ; сумма += элемент
        ADD   R7, R1     ; счётчик++ (флаги)
        JL    loop       ; пока счётчик < 0
; G13
        ADD   R9, R3     ; R9 = адрес результата
        NOP 2
; G14
        NOP 3
; G15
        STORE R4, (R3)   ; сумма
        ADD   R9, R1
        NOP
; G16
        NOP 3
; G17
        STORE R8, (R9)   ; число итераций
        NOP
        HALT
