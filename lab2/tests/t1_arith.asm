; Тест 1. Арифметика, LOAD/STORE, параллельная работа трёх конвейеров.
; Переходов нет. Проверяются ADD/SUB (в т.ч. с переполнением и отрицательным
; результатом), одновременная запись в память из трёх конвейеров.
; Каждая строка "; Gn" - группа из трёх команд, выбираемая за один такт.
; Результат команды используется не раньше, чем через одну группу.

.data
.org 0
        .word 1          ; 0: константа 1
        .word 1000       ; 1: A
        .word 234        ; 2: B
        .word 0x7FFF     ; 3: C = 32767
.org 8
        .fill 8, 0xDEAD  ; 8..15: сюда пишутся результаты

.text
; G0
        LOAD  R1, (R0)   ; R1 = 1
        NOP
        NOP
; G1
        NOP 3
; G2
        LOAD  R4, (R1)   ; R4 = A = 1000
        ADD   R2, R1     ; R2 = 1
        ADD   R3, R1     ; R3 = 1
; G3
        NOP 3
; G4
        ADD   R2, R1     ; R2 = 2
        ADD   R3, R3     ; R3 = 2
        ADD   R8, R1     ; R8 = 1
; G5
        NOP 3
; G6
        LOAD  R5, (R2)   ; R5 = B = 234
        ADD   R3, R1     ; R3 = 3
        ADD   R8, R8     ; R8 = 2
; G7
        NOP 3
; G8
        LOAD  R6, (R3)   ; R6 = C = 32767
        ADD   R8, R8     ; R8 = 4
        ADD   R7, R4     ; R7 = A
; G9
        NOP 3
; G10
        ADD   R8, R8     ; R8 = 8  (указатель результатов)
        ADD   R7, R5     ; R7 = A + B = 1234
        SUB   R4, R5     ; R4 = A - B = 766
; G11
        NOP 3
; G12
        ADD   R9, R8     ; R9  = 8
        ADD   R10, R8    ; R10 = 8
        ADD   R11, R8    ; R11 = 8
; G13
        ADD   R6, R1     ; R6 = 32767 + 1 = -32768 (переполнение)
        SUB   R5, R7     ; R5 = 234 - 1234 = -1000
        ADD   R12, R8    ; R12 = 8
; G14
        ADD   R10, R1    ; R10 = 9
        ADD   R11, R2    ; R11 = 10
        NOP
; G15
        STORE R7, (R8)   ; DM[8] = 1234  -+ конвейеры 0 и 2 пишут в один адрес
        ADD   R12, R3    ; R12 = 11       | в одном такте: побеждает более
        STORE R4, (R9)   ; DM[8] = 766   -+ поздняя команда (766)
; G16
        NOP 3
; G17
        STORE R7, (R10)  ; DM[9]  = 1234  -+
        STORE R6, (R11)  ; DM[10] = 8000h  | три записи в память
        STORE R5, (R12)  ; DM[11] = -1000 -+ в одном такте
; G18
        HALT
        NOP
        NOP
